fn ok(bytes: &[u8]) -> Insn {
    decode(bytes, RIP).unwrap_or_else(|e| panic!("{bytes:02x?}: {e:?}"))
}

#[test]
fn valid_vectors() {
    for &(bytes, len, class) in VALID {
        let insn = ok(bytes);
        assert_eq!(insn.len, len, "{bytes:02x?}");
        assert_eq!(insn.class, class, "{bytes:02x?}");
        // Trailing bytes do not change the result.
        let mut longer = bytes.to_vec();
        longer.extend_from_slice(&[0xcc; 16]);
        assert_eq!(decode(&longer, RIP), Ok(insn), "{bytes:02x?}");
    }
}

#[test]
fn invalid_vectors() {
    for &bytes in INVALID {
        assert_eq!(
            decode(bytes, RIP),
            Err(DecodeError::Invalid),
            "{bytes:02x?}"
        );
    }
}

#[test]
fn truncated_vectors() {
    for &bytes in TRUNCATED {
        assert_eq!(
            decode(bytes, RIP),
            Err(DecodeError::Truncated),
            "{bytes:02x?}"
        );
    }
}

#[test]
fn length_limit() {
    let mut fifteen = vec![0x66; 14];
    fifteen.push(0x90);
    assert_eq!(ok(&fifteen).len, 15);
    let mut sixteen = vec![0x66; 15];
    sixteen.push(0x90);
    assert_eq!(decode(&sixteen, RIP), Err(DecodeError::Invalid));
    // Running out at byte 16 is too long, not truncated.
    assert_eq!(decode(&[0x66; 15], RIP), Err(DecodeError::Invalid));
    let mut long_imm = vec![0x66; 6];
    long_imm.extend_from_slice(&[0x48, 0xb8, 1, 2, 3, 4, 5, 6, 7, 8]);
    assert_eq!(decode(&long_imm, RIP), Err(DecodeError::Invalid));
}

#[test]
fn fs_absolute_fields() {
    let i = ok(&[0x64, 0x48, 0x8b, 0x04, 0x25, 0x28, 0x00, 0x00, 0x00]);
    assert_eq!(i.prefixes(), &[0x64]);
    assert_eq!(i.rex, 0x48);
    assert!(i.rex_w());
    assert_eq!(i.map, Map::OneByte);
    assert_eq!(i.opcode, 0x8b);
    assert_eq!(i.modrm, Some(0x04));
    assert_eq!(i.sib, Some(0x25));
    assert_eq!((i.disp, i.disp_size), (0x28, 4));
    assert_eq!(i.imm_size, 0);
    assert!(i.seg_fs && !i.seg_gs && !i.rip_relative);
    assert_eq!(i.target, None);
    assert_eq!(i.rip, RIP);
}

#[test]
fn gs_and_segment_order() {
    // The last segment prefix wins.
    let i = ok(&[0x64, 0x65, 0x8b, 0x00]);
    assert!(i.seg_gs && !i.seg_fs);
    assert_eq!(i.prefixes(), &[0x64, 0x65]);
    let i = ok(&[0x3e, 0xff, 0xe0]);
    assert!(!i.seg_fs && !i.seg_gs);
    assert_eq!(i.prefixes(), &[0x3e]);
}

#[test]
fn rip_relative_fields() {
    let i = ok(&[0x48, 0x8b, 0x05, 0xf0, 0xff, 0xff, 0xff]);
    assert!(i.rip_relative);
    assert_eq!(i.sib, None);
    assert_eq!((i.disp, i.disp_size), (-0x10, 4));
    assert_eq!(i.rip_target(), Some(RIP + 7 - 0x10));
    let i = ok(&[0xff, 0x15, 0x10, 0x00, 0x00, 0x00]);
    assert!(i.rip_relative);
    assert_eq!(i.rip_target(), Some(RIP + 6 + 0x10));
    // SIB with base 101 and mod 00 is absolute, not RIP-relative.
    let i = ok(&[0x48, 0x8b, 0x04, 0xcd, 0x00, 0x10, 0x00, 0x00]);
    assert!(!i.rip_relative);
    assert_eq!(i.sib, Some(0xcd));
    assert_eq!((i.disp, i.disp_size), (0x1000, 4));
    // mod 01 with rm 101 is [rbp+disp8].
    let i = ok(&[0x8b, 0x45, 0xf8]);
    assert!(!i.rip_relative);
    assert_eq!((i.disp, i.disp_size), (-8, 1));
}

#[test]
fn immediates() {
    let i = ok(&[0x48, 0xb8, 1, 2, 3, 4, 5, 6, 7, 8]);
    assert_eq!((i.imm, i.imm_size), (0x0807_0605_0403_0201, 8));
    let i = ok(&[0x66, 0xb8, 0x34, 0x12]);
    assert_eq!((i.imm, i.imm_size), (0x1234, 2));
    let i = ok(&[0x48, 0xc7, 0xc0, 0xff, 0xff, 0xff, 0xff]);
    assert_eq!((i.imm, i.imm_size), (0xffff_ffff, 4));
    assert_eq!(i.imm_sext(), -1);
    let i = ok(&[0xf6, 0xc0, 0x01]);
    assert_eq!((i.imm, i.imm_size), (1, 1));
    let i = ok(&[0xc8, 0x10, 0x00, 0x01]);
    assert_eq!((i.imm, i.imm_size), (0x01_0010, 3));
    let i = ok(&[0xc2, 0x08, 0x00]);
    assert_eq!((i.imm, i.imm_size), (8, 2));
}

#[test]
fn moffs() {
    let i = ok(&[0xa0, 1, 2, 3, 4, 5, 6, 7, 8]);
    assert_eq!((i.disp as u64, i.disp_size), (0x0807_0605_0403_0201, 8));
    assert_eq!((i.modrm, i.imm_size), (None, 0));
    let i = ok(&[0x67, 0xa1, 0x78, 0x56, 0x34, 0x12]);
    assert_eq!((i.disp, i.disp_size), (0x1234_5678, 4));
    let i = ok(&[0x64, 0x48, 0xa1, 0x28, 0, 0, 0, 0, 0, 0, 0]);
    assert!(i.seg_fs);
    assert_eq!((i.disp, i.disp_size, i.len), (0x28, 8, 11));
}

#[test]
fn branch_targets() {
    assert_eq!(ok(&[0xeb, 0xfe]).target, Some(RIP));
    assert_eq!(ok(&[0x74, 0x10]).target, Some(RIP + 0x12));
    let jne = ok(&[0x0f, 0x85, 0xf0, 0xff, 0xff, 0xff]);
    assert_eq!(jne.target, Some(RIP + 6 - 0x10));
    assert_eq!(ok(&[0xe8, 0, 0, 0, 0]).target, Some(RIP + 5));
    assert_eq!(ok(&[0xe9, 0x00, 0x01, 0, 0]).target, Some(RIP + 0x105));
    assert_eq!(ok(&[0xe3, 0x05]).target, Some(RIP + 7));
    assert_eq!(ok(&[0xff, 0xd0]).target, None);
    assert_eq!(ok(&[0xc3]).target, None);
}

